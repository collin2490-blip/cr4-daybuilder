/*
 * CR.4 Daybuilder — service worker
 * Cachet alle bestanden van de app bij het eerste bezoek, zodat de app
 * daarna volledig offline werkt. Geen externe afhankelijkheden, geen
 * push-infrastructuur — alleen offline-cache + installeerbaarheid.
 */
const CACHE_NAME = 'cr4-daybuilder-v1.5';
const ASSETS = [
  './',
  './index.html',
  './manifest.json',
  './icon-192.png',
  './icon-512.png'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(ASSETS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE_NAME).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  // v1.4: de app-pagina zelf eerst via het netwerk (als er verbinding is),
  // zodat een nieuwe versie meteen binnenkomt bij één keer openen online.
  // Geen verbinding -> gewoon de opgeslagen versie (volledig offline).
  if (event.request.mode === 'navigate') {
    event.respondWith(
      fetch(event.request)
        .then(response => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put('./index.html', copy));
          return response;
        })
        .catch(() => caches.match('./index.html').then(r => r || caches.match('./')))
    );
    return;
  }
  event.respondWith(
    caches.match(event.request).then(cached => {
      if (cached) return cached;
      return fetch(event.request)
        .then(response => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(event.request, copy));
          return response;
        })
        .catch(() => caches.match('./index.html'));
    })
  );
});
